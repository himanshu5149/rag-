// Get translation with variable substitution
export function t(lang: LangCode, key: keyof Translations, vars?: Record<string, string | number>): string {
  let text = T[lang]?.[key] ?? T.en[key];
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

// Detect user's browser language
export function detectLanguage(): LangCode {
  if (typeof navigator === 'undefined') return 'en';
  const lang = navigator.language.split('-')[0];
  const supported: LangCode[] = ['en', 'es', 'zh', 'hi', 'ar', 'fr', 'de', 'ja', 'pt', 'ru'];
  return supported.includes(lang as LangCode) ? (lang as LangCode) : 'en';
}
